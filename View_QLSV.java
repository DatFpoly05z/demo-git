public Model_QLSV readForm(){
    String ma;
    String ten;
    String email,soDienThoai;
    int gioiTinh;
    String diaChi;
    ma = txt_Ma.getText().trim();
    if(ma.isEmpty()){
        JOptionPane.showMessageDialog(this, "bạn chưa nhập tên");
        txt_Ma.requestFocus();
        return null;
    }
    ten = txt_Ten.getText().trim();
    email = txt_Email.getText().trim();
    soDienThoai = txt_SDT.getText().trim();
    if(rdo_Nam.isSelected())
        gioiTinh = 1;
    else
        gioiTinh = 0;
    diaChi = txt_DiaChi.getText().trim();
    return new Model_QLSV(ma, ten, email, soDienThoai, gioiTinh, diaChi);
}
