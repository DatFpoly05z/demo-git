    private void tbl_QLSVMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbl_QLSVMouseClicked
        // TODO add your handling code here:
        i = tbl_QLSV.getSelectedRow();
        txt_Ma.setText(tbl_QLSV.getValueAt(i, 0).toString());
        txt_Ten.setText(tbl_QLSV.getValueAt(i, 1).toString());
        txt_Email.setText(tbl_QLSV.getValueAt(i, 2).toString());
        txt_SDT.setText(tbl_QLSV.getValueAt(i, 3).toString());
        if(tbl_QLSV.getValueAt(i, 4).toString().equalsIgnoreCase("Nam"))
            rdo_Nam.setSelected(true);
        else
            rdo_Nu.setSelected(true);
        txt_DiaChi.setText(tbl_QLSV.getValueAt(i, 5).toString());
    }//GEN-LAST:event_tbl_QLSVMouseClicked

    private void btn_ThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_ThemActionPerformed
        // TODO add your handling code here:
        if(this.readForm()==null){
            JOptionPane.showMessageDialog(this, "thêm thất bại");
        }else{
            if(rp1.them(this.readForm())>0){
                JOptionPane.showMessageDialog(this, "thêm thành công");
                this.fillTable(rp1.getAll());
            }else
                JOptionPane.showMessageDialog(this, "Thêm thất bại");
        }
    }//GEN-LAST:event_btn_ThemActionPerformed

    private void btn_DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_DeleteActionPerformed
        // TODO add your handling code here
        i = tbl_QLSV.getSelectedRow();
        if(i == -1){
            JOptionPane.showMessageDialog(this, "bạn chưa chọn dòng cần xóa");
        }else{
            String ma = tbl_QLSV.getValueAt(i, 0).toString();
            if(rp1.xoa(ma)>0){
                JOptionPane.showMessageDialog(this, "Xóa thành công");
                this.fillTable(rp1.getAll());
            }else{
                JOptionPane.showMessageDialog(this, "Xóa thất bại");
            }
        }
    }//GEN-LAST:event_btn_DeleteActionPerformed

    private void btn_UpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_UpdateActionPerformed
        // TODO add your handling code here:
        i = tbl_QLSV.getSelectedRow();
        if(this.readForm()!= null){
            String ma = tbl_QLSV.getValueAt(i, 0).toString();
            if(rp1.upDate(ma, this.readForm())>0){
                JOptionPane.showMessageDialog(this, "Sửa thành công");
                this.fillTable(rp1.getAll());
                
            }else{
                JOptionPane.showMessageDialog(this, "Sửa thất bại ");
            }
                
        }
    }//GEN-LAST:event_btn_UpdateActionPerformed

